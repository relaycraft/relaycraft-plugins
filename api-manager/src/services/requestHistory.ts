/**
 * V2 metadata-only request history.
 *
 * Why: the legacy `request_history` key stored up to 30 full request+response
 * snapshots (headers, bodies, auth material) in a single KV value, which
 * pushes against the host quota (1 MiB per value, 50 MiB per plugin) and
 * keeps secrets around longer than needed.
 *
 * V2 persists one tiny record per entry under `request_history_v2_<id>`:
 * `{ id, sourceRequestId, createdAt, result: { status, time, totalBytes } }`.
 * Nothing else is stored — no URL, name, request/response headers or bodies,
 * error text, auth, or engine internals.
 *
 * Compatibility contract:
 * - The legacy `request_history` key is never written by append paths and is
 *   never migrated. Legacy entries keep their original snapshot/preview
 *   behavior when read.
 * - The only writes to the legacy key happen on explicit user actions that
 *   already existed: delete one item, clear all, clear-by-source. Those
 *   paths rewrite the legacy array minus the removed entries.
 * - Retention applies to V2 entries only: after each append, excess V2
 *   records beyond REQUEST_HISTORY_V2_LIMIT are removed — only keys this
 *   feature creates (the `request_history_v2_` prefix).
 */

export const REQUEST_HISTORY_V2_PREFIX = "request_history_v2_";
export const REQUEST_HISTORY_V2_LIMIT = 30;
const LEGACY_HISTORY_KEY = "request_history";

/** Minimal KV surface the host `api.storage` already provides. */
export interface HistoryKvStore {
  get(key: string): Promise<string | null>;
  set(key: string, value: string): Promise<void>;
  list(prefix: string): Promise<string[]>;
  delete(key: string): Promise<void>;
}

export interface RequestHistoryResultMeta {
  status: number;
  time: number;
  totalBytes: number;
}

/** What the caller supplies for a new entry; id and createdAt are caller-generated. */
export interface RequestHistoryAppendInput {
  id: string;
  sourceRequestId: string;
  createdAt: number;
  result: {
    status: unknown;
    time: unknown;
    totalBytes: unknown;
  };
}

export interface RequestHistoryItemV2 {
  id: string;
  sourceRequestId: string;
  createdAt: number;
  result: RequestHistoryResultMeta;
}

function finiteOrZero(value: unknown): number {
  const n = Number(value);
  return Number.isFinite(n) ? n : 0;
}

const KEY_SAFE_ID = /^[a-zA-Z0-9_-]+$/;
const MAX_KEY_LENGTH = 128;

/**
 * Host keys allow [a-zA-Z0-9-_], max 128 chars total. IDs are generated by
 * the caller and expected to already be safe — sanitize nothing: reject
 * anything else so distinct IDs can never alias onto the same record.
 */
function keyFor(id: string): string {
  const raw = String(id);
  if (!KEY_SAFE_ID.test(raw)) {
    throw new Error("request history id must match [a-zA-Z0-9_-]");
  }
  if (REQUEST_HISTORY_V2_PREFIX.length + raw.length > MAX_KEY_LENGTH) {
    throw new Error("request history id exceeds the storage key limit");
  }
  return REQUEST_HISTORY_V2_PREFIX + raw;
}

/**
 * Whitelist-normalize a parsed V2 record. Returns null for anything that is
 * not exactly the writer's shape — typed fields only, extra persisted keys
 * never reach the UI.
 */
function normalizeReadItem(parsed: unknown): RequestHistoryItemV2 | null {
  if (!parsed || typeof parsed !== "object") return null;
  const p = parsed as Record<string, unknown>;
  const result = p.result;
  if (typeof p.id !== "string" || !KEY_SAFE_ID.test(p.id)) return null;
  if (typeof p.sourceRequestId !== "string") return null;
  if (!Number.isFinite(p.createdAt)) return null;
  if (!result || typeof result !== "object") return null;
  const r = result as Record<string, unknown>;
  if (!Number.isFinite(r.status) || !Number.isFinite(r.time) || !Number.isFinite(r.totalBytes)) {
    return null;
  }
  return {
    id: p.id,
    sourceRequestId: p.sourceRequestId,
    createdAt: p.createdAt as number,
    result: {
      status: r.status as number,
      time: r.time as number,
      totalBytes: r.totalBytes as number,
    },
  };
}

function normalizeItem(input: RequestHistoryAppendInput): RequestHistoryItemV2 {
  return {
    id: String(input.id),
    sourceRequestId: String(input.sourceRequestId),
    createdAt: finiteOrZero(input.createdAt),
    result: {
      status: finiteOrZero(input.result?.status),
      time: finiteOrZero(input.result?.time),
      totalBytes: finiteOrZero(input.result?.totalBytes),
    },
  };
}

export class RequestHistoryService {
  private kv: HistoryKvStore;

  constructor(kv: HistoryKvStore) {
    this.kv = kv;
  }

  private async readLegacy(): Promise<any[]> {
    const raw = await this.kv.get(LEGACY_HISTORY_KEY);
    if (!raw) return [];
    try {
      const parsed = JSON.parse(raw);
      return Array.isArray(parsed) ? parsed : [];
    } catch {
      return [];
    }
  }

  private async writeLegacy(items: any[]): Promise<void> {
    await this.kv.set(LEGACY_HISTORY_KEY, JSON.stringify(items));
  }

  async listV2(): Promise<RequestHistoryItemV2[]> {
    const keys = await this.kv.list(REQUEST_HISTORY_V2_PREFIX);
    const items: RequestHistoryItemV2[] = [];
    for (const key of keys) {
      const raw = await this.kv.get(key);
      if (!raw) continue;
      try {
        const item = normalizeReadItem(JSON.parse(raw));
        if (item) items.push(item);
      } catch {
        // Broken entry: skip on read; it only disappears via explicit clear.
      }
    }
    return items;
  }

  /**
   * Persist one metadata-only record, then trim V2 entries beyond the cap.
   * Never touches the legacy key.
   */
  async append(input: RequestHistoryAppendInput): Promise<void> {
    const item = normalizeItem(input);
    await this.kv.set(keyFor(item.id), JSON.stringify(item));

    const items = await this.listV2();
    if (items.length <= REQUEST_HISTORY_V2_LIMIT) return;
    items.sort((a, b) => b.createdAt - a.createdAt || (a.id < b.id ? -1 : 1));
    for (const excess of items.slice(REQUEST_HISTORY_V2_LIMIT)) {
      await this.kv.delete(keyFor(excess.id));
    }
  }

  /** V2 + legacy merged, newest first, deduplicated by id (first wins). */
  async getMerged(): Promise<any[]> {
    const [v2, legacy] = await Promise.all([this.listV2(), this.readLegacy()]);
    const merged = [...v2, ...legacy];
    merged.sort((a, b) => finiteOrZero(b?.createdAt) - finiteOrZero(a?.createdAt));
    const seen = new Set<string>();
    return merged.filter((item) => {
      const id = String(item?.id ?? "");
      if (!id || seen.has(id)) return false;
      seen.add(id);
      return true;
    });
  }

  /** Explicit per-item delete: removes the id from BOTH stores. */
  async deleteById(id: string): Promise<void> {
    // An id that fails key validation can never be a V2 record — only the
    // legacy array can hold it.
    if (KEY_SAFE_ID.test(id)) {
      await this.kv.delete(keyFor(id));
    }
    const legacy = await this.readLegacy();
    if (legacy.some((x) => x?.id === id)) {
      await this.writeLegacy(legacy.filter((x) => x?.id !== id));
    }
  }

  /**
   * Explicit clear-all: wipes V2 keys and removes the legacy key entirely —
   * including malformed payloads `readLegacy()` cannot parse. The key is
   * only deleted when present.
   */
  async clearAll(): Promise<void> {
    const keys = await this.kv.list(REQUEST_HISTORY_V2_PREFIX);
    for (const key of keys) {
      await this.kv.delete(key);
    }
    if ((await this.kv.get(LEGACY_HISTORY_KEY)) !== null) {
      await this.kv.delete(LEGACY_HISTORY_KEY);
    }
  }

  /** Explicit clear for one request: removes matching entries in BOTH stores. */
  async clearBySource(sourceRequestId: string): Promise<void> {
    const items = await this.listV2();
    for (const item of items) {
      if (item.sourceRequestId === sourceRequestId) {
        await this.kv.delete(keyFor(item.id));
      }
    }
    const legacy = await this.readLegacy();
    if (legacy.some((x) => x?.sourceRequestId === sourceRequestId)) {
      await this.writeLegacy(legacy.filter((x) => x?.sourceRequestId !== sourceRequestId));
    }
  }
}
